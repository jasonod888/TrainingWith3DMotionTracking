"""Phase 5 cross-language contract: the workspace save body must satisfy the real API.

The payload is generated by the client code (`buildSaveBody`) for a concrete draft, posted
to the real review endpoint, and the stored reference is read back. A second generated
payload exercises the revision path.
"""
import json
import subprocess
from pathlib import Path
from unittest.mock import patch

import pytest

from test_music_media_validation import media, real_media_app
from test_music_review import proposal, review_body

ROOT = Path(__file__).resolve().parents[2]


def workspace_body(**payload):
    script = [
        '--import', './apps/web/node_modules/tsx/dist/loader.mjs',
        'tests/api/make_workspace_payload.ts', json.dumps(payload),
    ]
    result = subprocess.run(['node', *script], cwd=ROOT, capture_output=True, text=True, timeout=120)
    assert result.returncode == 0, result.stderr
    return json.loads(result.stdout)


def test_workspace_payload_round_trips_through_the_real_endpoints(tmp_path):
    with real_media_app(tmp_path) as (client, app, settings, store, mail):
        lesson_id, view, _lease, _base, _payload = proposal(client, app, media(tmp_path, 'audio'))
        sections = [{'id': 'whole', 'label': 'Whole lesson', 'start': 0, 'end': view['duration']}]
        body = workspace_body(events=view['events'], duration=view['duration'], draftId=view['draft_id'],
                              referenceSha256=view['reference']['sha256'], spans=view['spans'], sections=sections)
        assert body['draft_id'] == view['draft_id']
        assert body['reference_sha256'] == view['reference']['sha256']
        assert body['alignment']['passages'], 'the client must serialize the complete map'

        first = client.post(f'/api/lessons/{lesson_id}/music-draft/review', json=body)
        assert first.status_code == 200, first.text
        manifest = first.json()
        reference = json.loads(store.objects[manifest['reference']['key']])
        assert reference['alignment']['offset_seconds'] == 0.25
        assert reference['alignment']['anchors'] == body['alignment']['anchors']
        assert reference['alignment']['passages']
        assert reference['notation']['notation_version'] == 1
        assert 'verification_state_token' not in body, 'a plain draft needs no token'

        # Idempotent retry of the exact workspace payload is not a duplicate finalisation.
        retry = client.post(f'/api/lessons/{lesson_id}/music-draft/review', json=body)
        assert retry.status_code == 200
        assert retry.json()['revision_id'] == manifest['revision_id']

        # A later workspace save is a revision on the saved base.
        revision_body = workspace_body(
            events=view['events'], duration=view['duration'], draftId=view['draft_id'],
            referenceSha256=view['reference']['sha256'], spans=view['spans'], sections=sections,
            baseRevisionId=manifest['revision_id'])
        assert revision_body['base_revision_id'] == manifest['revision_id']
        with patch('apps.api.music_edit.storage_client', return_value=store):
            second = client.post(f'/api/lessons/{lesson_id}/music-revision', json=revision_body)
        assert second.status_code == 200, second.text
        assert second.json()['revision_id'] != manifest['revision_id']
        edited_reference = json.loads(store.objects[second.json()['reference']['key']])
        assert edited_reference['alignment']['passages']
        assert edited_reference['alignment']['offset_seconds'] == 0.25
        assert edited_reference['review']['edited_from_revision'] == manifest['revision_id']

        # An old client omitting notation/alignment must not delete the authored data.
        legacy_edit = {key: value for key, value in revision_body.items()
                       if key not in ('notation', 'alignment', 'offset_seconds')}
        legacy_edit['base_revision_id'] = second.json()['revision_id']
        legacy_edit['title'] = 'Old client save'
        with patch('apps.api.music_edit.storage_client', return_value=store):
            legacy = client.post(f'/api/lessons/{lesson_id}/music-revision', json=legacy_edit)
        assert legacy.status_code == 200, legacy.text
        retained = json.loads(store.objects[legacy.json()['reference']['key']])
        assert retained['notation']['notation_version'] == 1, 'authored notation was silently dropped'
        assert retained['alignment']['passages'], 'the saved map was silently dropped'

        # An old client that contradicts the retained notation is refused, not silently accepted.
        broken = {**legacy_edit, 'base_revision_id': legacy.json()['revision_id'],
                  'events': [{**event, 'pitch': 65} for event in legacy_edit['events']]}
        with patch('apps.api.music_edit.storage_client', return_value=store):
            refused = client.post(f'/api/lessons/{lesson_id}/music-revision', json=broken)
        assert refused.status_code == 422, refused.text
